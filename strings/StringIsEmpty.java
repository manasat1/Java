public class StringIsEmpty {

    public static void main(String[] args) {

        String s1 = "";
        String s2 = "Java";
        String s3 = " ";

        System.out.println("s1 is empty: " + s1.isEmpty());
        System.out.println("s2 is empty: " + s2.isEmpty());
        System.out.println("s3 is empty: " + s3.isEmpty());
    }
}
